#include "common/zhangR47ProductDomain.hpp"

#include <iostream>
#include <numeric>
#include <random>
#include <stdexcept>
#include <thread>

static void require(bool condition,const char* message)
{if(!condition) throw std::runtime_error(message);}

static void setLegacy(bool legacy)
{
#ifdef _WIN32
    _putenv_s("ZHANG_R51_BRIDGE_COLUMN_PLAN",legacy?"legacy":"");
#else
    if(legacy) ::setenv("ZHANG_R51_BRIDGE_COLUMN_PLAN","legacy",1);
    else ::unsetenv("ZHANG_R51_BRIDGE_COLUMN_PLAN");
#endif
}

static ZhangExactMatrix projected(const ZhangExactMatrix& h,const ZhangExactMatrix& t,
    std::size_t columns)
{
    ZhangExactColumnPlan plan(h,columns);plan.advance();
    ZhangExactColumnProjection replay(t);replay.advance(plan);
    return replay.image;
}

// Independent integer oracle for a*N0+b*N1=0. Its entire integer kernel is
// generated by (b/g,-a/g), proved by elementary coprime divisibility. This
// does not call production HNF, Smith, kernel, membership or plan functions.
static long long independentImageStep(long long a,long long b,long long t0,long long t1)
{
    const long long g=std::gcd(std::abs(a),std::abs(b));
    if(!g) return std::gcd(std::abs(t0),std::abs(t1));
    return std::abs(t0*(b/g)-t1*(a/g));
}

int main()
{
    setLegacy(false);
    std::mt19937 rng(20261020);
    std::size_t comparisons=0,interruptions=0,independent=0;
    for(int test=0;test<500;++test)
    {
        const int columns=1+rng()%8,rows=rng()%9,targets=1+rng()%4;
        ZhangExactMatrix h(rows,ZhangExactVector(columns)),t(targets,ZhangExactVector(columns));
        for(auto& row:h) for(auto& x:row) x=static_cast<int>(rng()%15)-7;
        for(auto& row:t) for(auto& x:row) x=static_cast<int>(rng()%11)-5;
        const auto legacy=zhangExactProjectedKernelColumns(h,t,columns);
        require(projected(h,t,columns)==legacy,"column-plan changed exact generator coordinates");
        ++comparisons;
        if(test<80)
        {
            // Multiple interruptions include pivot scans and scratch updates.
            ZhangExactColumnPlan plan(h,columns);
            int attempts=0;
            while(!plan.complete())
            {
                require(++attempts<20000,"resumable plan made no progress");
                ZhangExactWorkBudget budget;budget.maximumCheckpoints=23+rng()%29;
                ZhangScopedExactWorkBudget scope(budget);
                try {plan.advance();} catch(const ZhangExactWorkBudgetExceeded&) {++interruptions;}
            }
            ZhangExactColumnProjection replay(t);
            attempts=0;
            while(!replay.complete())
            {
                require(++attempts<20000,"resumable target made no progress");
                ZhangExactWorkBudget budget;budget.maximumCheckpoints=11+rng()%17;
                ZhangScopedExactWorkBudget scope(budget);
                try {replay.advance(plan);} catch(const ZhangExactWorkBudgetExceeded&) {++interruptions;}
            }
            require(replay.image==legacy,"resumed exact result differs from uninterrupted legacy");
        }
    }
    for(int a=-6;a<=6;++a) for(int b=-6;b<=6;++b)
    for(int t0=-3;t0<=3;++t0) for(int t1=-3;t1<=3;++t1)
    {
        auto image=projected({{a,b}},{{t0,t1}},2);
        long long gcd=0;
        for(const auto& x:image.front()) gcd=std::gcd(gcd,std::abs(x.convert_to<long long>()));
        require(gcd==independentImageStep(a,b,t0,t1),"independent primitive-kernel oracle mismatch");
        ++independent;
    }
    // Nonunit congruence is not saturated away: 2*Nold+Nlive=1 allows
    // Nlive=1+2*Z, not every integer. The homogeneous image has step two.
    const auto parity=projected({{2,1}},{{0,1}},2);
    require(parity.size()==1 && parity.front().size()==1 &&
        zhangExactAbs(parity.front().front())==2,"lost parity constraint");
    // Target-only unknown columns are free, not implicitly constrained zero.
    ZhangExactColumnPlan base({{2,1}},2);base.advance();
    ZhangExactColumnProjection extended({{0,1,3}});extended.advance(base);
    require(extended.image==zhangExactProjectedKernelColumns({{2,1,0}},{{0,1,3}},3),
        "appended free target column changed order or integer image");

    auto domain=std::make_shared<ZhangExactAffineIntegerQuotient>();
    domain->valid=true;domain->ambientDimension=3;
    domain->deterministicBasis={{2,1,0},{0,3,1}};
    const ZhangExactMatrix target={{1,2,3},{0,1,0}};
    ZhangExactColumnPlanDiagnostics first,second,other;
    const auto one=zhangProjectedKernelOnOwnedDomain(domain,target,&first);
    const auto two=zhangProjectedKernelOnOwnedDomain(domain,target,&second);
    require(one==two && !first.sharedPlanHit && second.sharedPlanHit && second.targetReplayHit,
        "immutable owner plan/replay not shared");
    const auto three=zhangProjectedKernelOnOwnedDomain(domain,{{1,0,0}},&other);
    require(three==zhangExactProjectedKernelColumns(domain->deterministicBasis,{{1,0,0}},3)
        && other.sharedPlanHit && other.buildCalls==1,"new target rebuilt the source factorization");
    auto distinct=std::make_shared<ZhangExactAffineIntegerQuotient>(*domain);
    ZhangExactColumnPlanDiagnostics distinctStats;
    zhangProjectedKernelOnOwnedDomain(distinct,target,&distinctStats);
    require(!distinctStats.sharedPlanHit,"different domain owners were incorrectly merged");
    setLegacy(true);
    ZhangExactColumnPlanDiagnostics legacyStats;
    require(zhangProjectedKernelOnOwnedDomain(domain,target,&legacyStats)==one && legacyStats.legacyOverride,
        "legacy diagnostic switch changed the mathematical result");
    setLegacy(false);
    ZhangExactMatrix parallelOutputs[4];
    std::thread workers[4];
    for(int i=0;i<4;++i) workers[i]=std::thread([&,i]() {
        parallelOutputs[i]=zhangProjectedKernelOnOwnedDomain(domain,target);});
    for(auto& worker:workers) worker.join();
    for(const auto& output:parallelOutputs) require(output==one,"shared plan parallel replay changed result");

    auto interruptedOwner=std::make_shared<ZhangExactAffineIntegerQuotient>(*domain);
    bool interrupted=false;
    {
        ZhangExactWorkBudget budget;budget.maximumCheckpoints=5;
        ZhangScopedExactWorkBudget scope(budget);
        try {zhangProjectedKernelOnOwnedDomain(interruptedOwner,target);}
        catch(const ZhangExactWorkBudgetExceeded&) {interrupted=true;}
    }
    ZhangExactColumnPlanDiagnostics resumedStats;
    require(interrupted && zhangProjectedKernelOnOwnedDomain(interruptedOwner,target,&resumedStats)==one
        && resumedStats.sharedPlanHit,"cancelled owned-domain plan did not survive its call");

    // Compare the actual verified-domain entry point with the old complete
    // frame, including nonzero affine origin and an appended unknown column.
    auto feasible=std::make_shared<const ZhangExactAffineIntegerQuotient>(
        zhangExactAffineIntegerQuotient({{2,1}},{1},2,ZhangExactQuotientWork::PARTICULAR_ONLY));
    const ZhangExactMatrix extendedTargets={{0,1,3},{2,0,-1}};
    const auto verified=zhangR47CompileTargetOnVerifiedDomain(extendedTargets,feasible,3);
    const auto original=zhangR47CompileProductSearchFrame(extendedTargets,{{2,1,0}},{1},3,
        ZhangProductFrameWork::IMAGE_GENERATORS_ONLY);
    require(feasible->valid && verified.valid && original.valid &&
        verified.columns==original.columns && verified.searchRank==original.searchRank &&
        verified.imageGenerators==original.imageGenerators &&
        verified.affine->particularSolution==original.affine->particularSolution,
        "verified-domain frame changed origin/image/column coordinates");

    // Exhaustion must happen before an operation commit, never leaving a
    // partially transformed matrix that could later certify another result.
    ZhangExactColumnPlanLimits bounds;bounds.maximumOperations=0;
    bool limited=false;
    try {ZhangExactColumnPlan small({{2,1}},2,bounds);small.advance();}
    catch(const ZhangExactColumnPlanLimitExceeded&) {limited=true;}
    require(limited,"journal resource limit was ignored");
    require(ZhangExactColumnPlan::totalResidentMatrixBytes()==0,
        "completed/cancelled plan leaked a resident matrix reservation");
    std::cout<<"exact-column-plan: legacy_comparisons="<<comparisons
        <<" independent_cases="<<independent<<" safe_interruptions="<<interruptions
        <<" owner_cache_and_nonunit_checks=passed\n";
}
